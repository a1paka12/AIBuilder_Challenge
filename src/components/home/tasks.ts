/*
 * 첫 화면 업무 목록 — "업무 바로가기" 타일과 "업무별 안내" 상세 블록이 같이 쓴다.
 * 문구 원칙: AI는 정리만(판단·보장 문구 금지) · 지어낸 숫자·후기 없음 · 특정 변호사 소개·알선 없음(변호사 조건 추천은 가상 프로필 시연) · 가격은 가설이고 결제 미연결.
 * 숫자는 PRD 예시(780,000 / 300,000 / 250,000 / 550,000)와 가격 가설(4,900 / 2,900)만 쓴다.
 */

export interface HomeTask {
  route: Route
  icon: TaskIconName
  /** 업무 이름 (타일 · 상세 제목) */
  name: string
  /** 타일 한 줄 설명 */
  short: string
  /** 무료/유료 배지 글자 */
  badge: string
  /** 배지 색: ok(무료·진행 중) / 없음(안내·유료) */
  badgeTone?: 'ok'
  /** 상세: 무엇을 해 주나 */
  what: string
  /** 상세: AI가 하는 일 — 없으면 안내 전용 블록(가격·처리방침)으로 짧게 그린다 */
  ai?: string
  /** 상세: 내가 하는 일 */
  me?: string
  /** 상세: 비용 */
  cost?: string
  /** 상세 보기 버튼 이름 — 같은 이름 버튼이 여러 개라 대상 이름을 붙인다 */
  detailLabel: string
  /** false 면 '업무 바로가기' 타일에서 뺀다(상세 안내에는 남음) — 타일 그리드가 빈칸 없이 맞도록 */
  tile?: boolean
}

